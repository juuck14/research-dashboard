"""Independent enumeration audit of owner's channel model, not imported."""
from pathlib import Path
import csv,json
import numpy as np

HERE=Path(__file__).resolve().parent
ROOT=HERE.parents[2]

def enumerate_law(a,b):
    triple=np.zeros((3,3,3))
    emit=lambda x,z: a*(x==z)+(1-a)/3
    transition=lambda s,z: b*(s==z)+(1-b)/3
    for z in range(3):
        for zp in range(3):
            for i in range(3):
                for j in range(3):
                    for k in range(3):
                        triple[i,j,k]+=emit(i,z)*transition(zp,z)*emit(j,zp)*emit(k,z)/3
    return triple.sum(axis=2),triple

params=[]
for c in [.02,.16,.5,.9]:
    for a in np.linspace(np.sqrt(c),1.,11):params.append((a,c/a**2))
params.extend(np.random.default_rng(9319).uniform(.02,.99,(100,2)))
maximum={"pair":0.,"repeat":0.,"total_mass":0.}
for a,b in params:
    pair,triple=enumerate_law(a,b)
    c=a*a*b
    target=np.full((3,3),(1-c)/9)+np.eye(3)*c/3
    predicted=(1+2*a*a+4*c+2*a*c)/(3*(1+2*c))
    maximum["pair"]=max(maximum["pair"],float(abs(pair-target).max()))
    maximum["repeat"]=max(maximum["repeat"],abs(triple[0,0,0]/pair[0,0]-predicted))
    maximum["total_mass"]=max(maximum["total_mass"],abs(triple.sum()-1))
assert max(maximum.values())<1e-12

with (ROOT/"pair-uncertainty/results/finite_sample.csv").open() as f: rows=list(csv.DictReader(f))
groups={}
for row in rows:groups.setdefault((row["split"],row["n"],row["seed"]),[]).append(row)
err_c=err_loss=0.
for group in groups.values():
    assert len(group)==3
    cs=[float(r["c_hat"]) for r in group]
    err_c=max(err_c,max(cs)-min(cs))
    unknown=[r for r in group if r["policy"]!="known_positive_b"]
    err_loss=max(err_loss,abs(float(unknown[0]["pair_excess_logloss"])-float(unknown[1]["pair_excess_logloss"])))
assert err_c<1e-15 and err_loss<1e-12
summary={"enumerated_conditions":len(params),"random_confirmation_seed":9319,"max_errors":maximum,"finite_datasets_audited":len(groups),"finite_predictions_audited":len(rows),"same_dataset_max_c_hat_difference":err_c,"unknown_policy_max_pair_risk_difference":err_loss,"note":"expected repeat risk uses oracle law; held-out repeat samples were not generated by owner's finite-sample code"}
(HERE/"results/owner_audit.json").write_text(json.dumps(summary,indent=2)+"\n")
print(json.dumps(summary,indent=2))
